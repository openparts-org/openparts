"""MoonBit types for every JSON document openparts-server returns.

  python3 gen_api_types.py SCHEMA.json OUT.mbt

SCHEMA.json is the `$defs` map the server's `export_schemas` test
writes (schemars, from the Rust types themselves); OUT.mbt gets one
`pub(all)` struct per object schema and one enum per string enum, each
with an explicit `@json.FromJson` impl that follows serde: a missing or
`null` optional field is `None`, a field with a serde default decodes to
it, enum values are the snake_case wire strings (`Enum::wire` gives them
back). Run through web/scripts/gen-api-types.sh.
"""

import json
import re
import sys

# MoonBit keywords and reserved words that can't be field names.
RESERVED = {
    "type", "method", "package", "module", "ref", "use", "where", "match",
    "fn", "let", "mut", "enum", "struct", "trait", "impl", "test", "in",
    "for", "loop", "if", "else", "while", "break", "continue", "return",
    "raise", "try", "catch", "pub", "priv", "with", "guard", "async",
    "is", "as", "extern", "const", "derive", "import", "true", "false",
    "local", "move", "static", "super", "unsafe", "await", "dyn", "abstract",
    "do", "final", "macro", "override", "typeof", "virtual", "yield",
    "alias", "assert", "recur", "sealed", "lazy", "init", "main", "defer",
    "register", "using", "readonly", "noraise",
}

HEADER = """\
// GENERATED by web/scripts/gen-api-types.sh from the server's Rust
// types (schemars JSON Schema). Do not edit; CI fails if it is stale.

"""


def field_ident(name):
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if ident[0].isdigit():
        ident = "x" + ident
    if ident in RESERVED:
        ident += "_"
    return ident


def ctor(value):
    # Signed axis names ("+x", "-y") keep their sign.
    value = re.sub(r"^\+", "plus_", re.sub(r"^-", "minus_", value))
    parts = re.split(r"[^0-9a-zA-Z]+", value)
    name = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return name if name[0].isalpha() else "V" + name


def ref_name(schema):
    return schema["$ref"].rsplit("/", 1)[1]


def enum_values(schema):
    """The wire strings of a string enum schema, or None."""
    if "enum" in schema and schema.get("type") == "string":
        return list(schema["enum"])
    if "oneOf" in schema:
        out = []
        for alt in schema["oneOf"]:
            if alt.get("type") != "string":
                return None
            if "const" in alt:
                out.append(alt["const"])
            elif "enum" in alt:
                out.extend(alt["enum"])
            else:
                return None
        return out
    return None


def split_null(schema):
    """(inner schema, nullable)."""
    t = schema.get("type")
    if isinstance(t, list) and "null" in t:
        rest = [x for x in t if x != "null"]
        inner = dict(schema, type=rest[0] if len(rest) == 1 else rest)
        return inner, True
    for key in ("anyOf", "oneOf"):
        alts = schema.get(key)
        if alts and any(a.get("type") == "null" for a in alts):
            rest = [a for a in alts if a.get("type") != "null"]
            if len(rest) == 1:
                return rest[0], True
    return schema, False


DEFS = {}


def inlined(schema):
    """A transparent list type (`ParameterValues`) is used as its list."""
    return schema.get("type") == "array" and "items" in schema


def mbt_type(schema, where):
    if "$ref" in schema:
        name = ref_name(schema)
        if inlined(DEFS.get(name, {})):
            return mbt_type(DEFS[name], where)
        return name
    t = schema.get("type")
    if t == "string":
        return "String"
    if t == "boolean":
        return "Bool"
    if t == "integer":
        return "Int"
    if t == "number":
        return "Double"
    if t == "array":
        return f"Array[{mbt_type(schema['items'], where)}]"
    if t == "object" and "properties" not in schema:
        return f"Map[String, {mbt_type(schema['additionalProperties'], where)}]"
    sys.exit(f"{where}: unsupported schema {json.dumps(schema)[:200]}")


def gen_enum(name, values, out):
    ctors = [ctor(v) for v in values]
    out.append("///|\n#derive(Eq, Debug)\npub(all) enum %s {\n" % name)
    out.extend(f"  {c}\n" for c in ctors)
    out.append("}\n\n")
    out.append(
        f"///|\n/// The wire (JSON) string.\npub fn {name}::wire(self : {name}) -> String {{\n  match self {{\n"
    )
    out.extend(f'    {c} => "{v}"\n' for c, v in zip(ctors, values))
    out.append("  }\n}\n\n")
    out.append(
        f"///|\n/// Every value, in declaration order.\npub fn {name}::all() -> Array[{name}] {{\n  [{', '.join(ctors)}]\n}}\n\n"
    )
    out.append(
        f"///|\npub impl @json.FromJson for {name} with from_json(json, path) {{\n  match json {{\n"
    )
    out.extend(f'    String("{v}") => {c}\n' for c, v in zip(ctors, values))
    out.append(f'    _ => raise @json.JsonDecodeError((path, "expected a {name}"))\n  }}\n}}\n\n')


def gen_struct(name, schema, out):
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    fields, decoders = [], []
    for key, prop in props.items():
        ident = field_ident(key)
        inner, nullable = split_null(prop)
        ty = mbt_type(inner, f"{name}.{key}")
        default = prop.get("default", "absent")
        if key in required and not nullable:
            fields.append((ident, ty))
            decoders.append(f'{ident}: field(obj, "{key}", path)')
        elif not nullable and default == [] and ty.startswith("Array["):
            fields.append((ident, ty))
            decoders.append(f'{ident}: field_or(obj, "{key}", path, [])')
        elif not nullable and default == {} and ty.startswith("Map["):
            fields.append((ident, ty))
            decoders.append(f'{ident}: field_or(obj, "{key}", path, {{}})')
        else:
            fields.append((ident, f"{ty}?"))
            decoders.append(f'{ident}: opt_field(obj, "{key}", path)')
    doc = schema.get("description")
    out.append("///|\n")
    if doc:
        out.extend(f"/// {line}".rstrip() + "\n" for line in doc.splitlines())
    out.append(f"#derive(Eq)\npub(all) struct {name} {{\n")
    out.extend(f"  {i} : {t}\n" for i, t in fields)
    out.append("}\n\n")
    out.append(f"///|\npub impl @json.FromJson for {name} with from_json(json, path) {{\n")
    out.append(
        f'  guard json is Object(obj) else {{\n    raise @json.JsonDecodeError((path, "expected a {name} object"))\n  }}\n'
    )
    if decoders:
        out.append("  {\n")
        out.extend(f"    {d},\n" for d in decoders)
        out.append("  }\n}\n\n")
    else:
        out.append(f"  ignore(obj)\n  {{  }}\n}}\n\n")


def main():
    defs = json.load(open(sys.argv[1]))
    DEFS.update(defs)
    out = [HEADER]
    for name in sorted(defs):
        schema = defs[name]
        values = enum_values(schema)
        if values is not None:
            gen_enum(name, values, out)
        elif schema.get("type") == "object" and "properties" in schema:
            gen_struct(name, schema, out)
        elif inlined(schema):
            continue
        else:
            sys.exit(f"{name}: unsupported top-level schema")
    open(sys.argv[2], "w").write("".join(out))


main()
