        assert!(text.contains("(pad \"2\" smd custom (at 1.000 -1.000) (size 0.250 0.250)"));
        assert!(text.contains("(primitives (gr_poly (pts (xy -0.5000 0.5000) (xy 0.5000 0.5000) (xy 0.0000 -0.5000)) (width 0) (fill yes)))"));
