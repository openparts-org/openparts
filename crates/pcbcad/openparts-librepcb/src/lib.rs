//! openparts-librepcb: LibrePCB adapter behind the openparts-pcbcad IR
//! (Architecture Specification section 12/13). Unlike KiCad's single
//! `.kicad_sym`/`.kicad_mod` files, a usable LibrePCB library element
//! requires four linked element types -- Symbol, Package, Component,
//! and Device -- each its own UUID-named directory inside a `.lplib`
//! library directory. `generate_library` produces the full file set for
//! one part in one call.
//!
//! Format reverse-engineered from real files in LibrePCB's own official
//! base library (github.com/LibrePCB-Libraries/LibrePCB_Base.lplib) and
//! the authoritative `SignalRole` enum in LibrePCB's own source
//! (libs/librepcb/core/types/signalrole.h) -- not guessed from memory,
//! per this project's research discipline. Not independently verified
//! against a real LibrePCB install (none available in this
//! environment); a stretch goal for whoever picks this up next.

mod uuid_gen;

use openparts_pcbcad::{GraphicKind, PcbFootprint, PcbSymbol, PinElectricalType, PinOrientation};
use uuid::Uuid;

/// One file to write, with a path relative to the library's root
/// directory (e.g. `sym/<uuid>/symbol.lp`).
#[derive(Debug, Clone, PartialEq)]
pub struct LpFile {
    pub path: String,
    pub content: String,
}

/// Fixed generation timestamp (not a real creation date -- a stable
/// placeholder so output is byte-reproducible, same policy as
/// openparts-step's FILE_NAME timestamp).
const GENERATED_TIMESTAMP: &str = "2026-01-01T00:00:00Z";

fn pin_role(t: PinElectricalType) -> &'static str {
    match t {
        PinElectricalType::Input => "input",
        PinElectricalType::Output => "output",
        PinElectricalType::Bidirectional => "inout",
        PinElectricalType::PowerIn => "power",
        PinElectricalType::Passive => "passive",
        // LibrePCB's SignalRole has no "no connect"/"unspecified" role
        // (only passive/power/input/output/inout/opendrain) -- "passive"
        // is the closest neutral fit for a pin that carries no defined
        // electrical direction, matching common EDA-tool convention for
        // reserved/NC pins. Not a verbatim spec mapping.
        PinElectricalType::NoConnect | PinElectricalType::Unspecified => "passive",
    }
}

fn pin_rotation(o: PinOrientation) -> f64 {
    // Same angle convention as openparts-kicad's orientation_angle:
    // rotation is the direction the pin's free end points away from its
    // base position.
    match o {
        PinOrientation::Left => 0.0,
        PinOrientation::Bottom => 90.0,
        PinOrientation::Right => 180.0,
        PinOrientation::Top => 270.0,
    }
}

fn fmt_uuid(u: Uuid) -> String {
    u.to_string()
}

fn render_symbol(mpn: &str, symbol: &PcbSymbol, sym_uuid: Uuid, cmpcat_uuid: Uuid) -> String {
    let mut out = String::new();
    out.push_str(&format!("(librepcb_symbol {}\n", fmt_uuid(sym_uuid)));
    out.push_str(&format!(" (name \"{mpn}\")\n"));
    out.push_str(" (description \"Generated by OpenParts from Canonical Data.\")\n");
    out.push_str(" (keywords \"\")\n");
    out.push_str(" (author \"OpenParts\")\n");
    out.push_str(" (version \"0.1\")\n");
    out.push_str(&format!(" (created {GENERATED_TIMESTAMP})\n"));
    out.push_str(" (deprecated false)\n");
    out.push_str(" (generated_by \"\")\n");
    out.push_str(&format!(" (category {})\n", fmt_uuid(cmpcat_uuid)));
    out.push_str(" (grid_interval 2.54)\n");

    for pin in &symbol.pins {
        let pin_uuid = uuid_gen::derive(&format!("sym-pin:{mpn}:{}", pin.number));
        out.push_str(&format!(
            " (pin {} (name \"{}\")\n",
            fmt_uuid(pin_uuid),
            pin.name
        ));
        out.push_str(&format!(
            "  (position {:.2} {:.2}) (rotation {:.1}) (length {:.2})\n",
            pin.position.x,
            pin.position.y,
            pin_rotation(pin.orientation),
            pin.length
        ));
        out.push_str("  (name_position 2.5 0.0) (name_rotation 0.0) (name_height 2.0)\n");
        out.push_str("  (name_align left bottom)\n");
        out.push_str(" )\n");
    }

    for (i, graphic) in symbol.graphics.iter().enumerate() {
        let GraphicKind::Rectangle { start, end } = graphic.kind;
        let poly_uuid = uuid_gen::derive(&format!("sym-outline:{mpn}:{i}"));
        out.push_str(&format!(
            " (polygon {} (layer sym_outlines)\n",
            fmt_uuid(poly_uuid)
        ));
        out.push_str("  (width 0.2) (fill false) (grab_area true)\n");
        out.push_str(&format!(
            "  (vertex (position {:.2} {:.2}) (angle 0.0))\n",
            start.x, start.y
        ));
        out.push_str(&format!(
            "  (vertex (position {:.2} {:.2}) (angle 0.0))\n",
            end.x, start.y
        ));
        out.push_str(&format!(
            "  (vertex (position {:.2} {:.2}) (angle 0.0))\n",
            end.x, end.y
        ));
        out.push_str(&format!(
            "  (vertex (position {:.2} {:.2}) (angle 0.0))\n",
            start.x, end.y
        ));
        out.push_str(&format!(
            "  (vertex (position {:.2} {:.2}) (angle 0.0))\n",
            start.x, start.y
        ));
        out.push_str(" )\n");

        let name_text_uuid = uuid_gen::derive(&format!("sym-name-text:{mpn}"));
        let value_text_uuid = uuid_gen::derive(&format!("sym-value-text:{mpn}"));
        out.push_str(&format!(
            " (text {} (layer sym_names) (height 2.5)\n",
            fmt_uuid(name_text_uuid)
        ));
        out.push_str(&format!(
            "  (align left bottom) (position {:.2} {:.2}) (rotation 0.0) (lock false)\n",
            start.x, end.y
        ));
        out.push_str("  (value \"{{NAME}}\")\n )\n");
        out.push_str(&format!(
            " (text {} (layer sym_values) (height 2.5)\n",
            fmt_uuid(value_text_uuid)
        ));
        out.push_str(&format!(
            "  (align left top) (position {:.2} {:.2}) (rotation 0.0) (lock false)\n",
            start.x, start.y
        ));
        out.push_str("  (value \"{{VALUE}}\")\n )\n");
    }

    out.push(')');
    out.push('\n');
    out
}

fn render_package(
    mpn: &str,
    footprint: &PcbFootprint,
    pkg_uuid: Uuid,
    fp_uuid: Uuid,
    pkgcat_uuid: Uuid,
    model_uuid: Option<Uuid>,
) -> String {
    let mut out = String::new();
    out.push_str(&format!("(librepcb_package {}\n", fmt_uuid(pkg_uuid)));
    out.push_str(&format!(" (name \"{mpn}\")\n"));
    out.push_str(" (description \"Generated by OpenParts from Mechanical Geometry.\")\n");
    out.push_str(" (keywords \"\")\n");
    out.push_str(" (author \"OpenParts\")\n");
    out.push_str(" (version \"0.1\")\n");
    out.push_str(&format!(" (created {GENERATED_TIMESTAMP})\n"));
    out.push_str(" (deprecated false)\n");
    out.push_str(" (generated_by \"\")\n");
    out.push_str(&format!(" (category {})\n", fmt_uuid(pkgcat_uuid)));
    out.push_str(&format!(" (assembly_type {})\n", assembly_type(footprint)));
    out.push_str(" (grid_interval 2.54)\n");
    out.push_str(" (min_copper_clearance 0.15)\n");

    for number in pad_numbers(footprint) {
        let pad_uuid = uuid_gen::derive(&format!("pkg-pad:{mpn}:{number}"));
        out.push_str(&format!(
            " (pad {} (name \"{number}\"))\n",
            fmt_uuid(pad_uuid)
        ));
    }

    // Package-level 3D model declaration, between pads and footprints
    // (order per librepcb-parts-generator's `Package.__str__`,
    // `Package3DModel` = `(3d_model <uuid> (name "..."))`).
    if let Some(model_uuid) = model_uuid {
        out.push_str(&format!(
            " (3d_model {} (name \"{mpn}\"))\n",
            fmt_uuid(model_uuid)
        ));
    }

    out.push_str(&format!(" (footprint {}\n", fmt_uuid(fp_uuid)));
    out.push_str("  (name \"default\")\n");
    out.push_str("  (description \"\")\n");
    // Identity transform: the STEP is generated from the same
    // MechanicalGeometry as the pads, and LibrePCB (like the IR and the
    // STEP) is Y-up, so no offset/rotation/flip is needed.
    out.push_str("  (3d_position 0.0 0.0 0.0) (3d_rotation 0.0 0.0 0.0)\n");
    // Footprint-level reference (`Footprint3DModel` = `(3d_model
    // <uuid>)`), right after 3d_position/3d_rotation and before pads.
    if let Some(model_uuid) = model_uuid {
        out.push_str(&format!("  (3d_model {})\n", fmt_uuid(model_uuid)));
    }
    // Silkscreen, documentation and courtyard drawings.
    let mut drawings: Vec<(&str, f64, openparts_pcbcad::FpShape)> = footprint
        .graphics
        .iter()
        .map(|g| {
            let layer = match g.layer {
                openparts_pcbcad::FpLayer::Silk => "top_legend",
                openparts_pcbcad::FpLayer::Fab => "top_documentation",
            };
            (layer, g.width, g.shape.clone())
        })
        .collect();
    if let Some(c) = &footprint.courtyard {
        drawings.push((
            "top_courtyard",
            openparts_pcbcad::COURTYARD_WIDTH,
            openparts_pcbcad::FpShape::Polygon(c.outline.clone()),
        ));
    }
    for (i, (layer, width, shape)) in drawings.iter().enumerate() {
        let uuid = fmt_uuid(uuid_gen::derive(&format!("fp-drawing:{mpn}:{i}")));
        let vertex = |p: &openparts_pcbcad::Point2| {
            format!("(vertex (position {:.3} {:.3}) (angle 0.0))", p.x, p.y)
        };
        match shape {
            openparts_pcbcad::FpShape::Line(a, b) => out.push_str(&format!(
                "  (polygon {uuid} (layer {layer}) (width {width:.3}) (fill false) (grab_area false) {} {})\n",
                vertex(a),
                vertex(b)
            )),
            openparts_pcbcad::FpShape::Polygon(points) => {
                // Closed: back to the first vertex.
                let mut v: Vec<String> = points.iter().map(vertex).collect();
                if let Some(first) = points.first() {
                    v.push(vertex(first));
                }
                out.push_str(&format!(
                    "  (polygon {uuid} (layer {layer}) (width {width:.3}) (fill false) (grab_area false) {})\n",
                    v.join(" ")
                ));
            }
            openparts_pcbcad::FpShape::Circle { center, radius } => out.push_str(&format!(
                "  (circle {uuid} (layer {layer}) (width {width:.3}) (fill {}) (grab_area false) (diameter {:.3}) (position {:.3} {:.3}))\n",
                *radius <= 0.15,
                radius * 2.0,
                center.x,
                center.y
            )),
        }
    }
    for pad in footprint
        .pads
        .iter()
        .filter(|p| p.mounting == openparts_mcad::Mounting::NonPlated)
    {
        // A non-plated hole is a footprint-level hole, not a pad.
        let d = pad
            .drill
            .expect("a non-plated hole must have a drill diameter");
        let uuid = uuid_gen::derive(&format!(
            "pkg-npth:{mpn}:{:.3}:{:.3}",
            pad.position.x, pad.position.y
        ));
        out.push_str(&format!(
            "  (hole {} (diameter {d:.3}) (vertex (position {:.3} {:.3}) (angle 0.0)))\n",
            fmt_uuid(uuid),
            pad.position.x,
            pad.position.y
        ));
    }
    for (i, pad) in footprint
        .pads
        .iter()
        .filter(|p| p.mounting != openparts_mcad::Mounting::NonPlated)
        .enumerate()
    {
        // Several footprint pads may share a number (and so a package
        // pad); each needs its own uuid.
        let pad_uuid = uuid_gen::derive(&format!("pkg-pad:{mpn}:{}", pad.number));
        let fp_pad_uuid = uuid_gen::derive(&format!("fp-pad:{mpn}:{}:{i}", pad.number));
        out.push_str(&format!(
            "  (pad {} (side top) (shape roundrect)\n",
            fmt_uuid(fp_pad_uuid)
        ));
        // LibrePCB has no separate "circle" pad shape -- a pad is
        // always `roundrect`, and `radius` (a 0.0-1.0 "how rounded"
        // scale, per LibrePCB/librepcb-parts-generator's own
        // `ShapeRadius`) controls how round it looks: 0.0 for
        // `PadShape::Rect`, 1.0 (fully rounded: a circle, or an obround
        // on a non-square pad) for `Circle` and `Oval`.
        let radius = match pad.shape {
            openparts_pcbcad::PadShape::Rect => 0.0,
            openparts_pcbcad::PadShape::Circle | openparts_pcbcad::PadShape::Oval => 1.0,
        };
        out.push_str(&format!(
            "   (position {:.3} {:.3}) (rotation 0.0) (size {:.3} {:.3}) (radius {radius:.1})\n",
            pad.position.x, pad.position.y, pad.size.0, pad.size.1
        ));
        out.push_str(
            "   (stop_mask auto) (solder_paste auto) (clearance 0.0) (function standard)\n",
        );
        out.push_str(&format!("   (package_pad {})\n", fmt_uuid(pad_uuid)));
        // LibrePCB has no separate through-hole pad type either -- a
        // pad becomes through-hole by attaching a `hole` child (a
        // single centered vertex for a plain round drill), matching
        // `PadHole`/`Vertex`'s own `__str__` output in
        // LibrePCB/librepcb-parts-generator's `entities/package.py`
        // and `entities/common.py` exactly.
        if pad.mounting == openparts_mcad::Mounting::ThroughHole {
            let drill = pad
                .drill
                .expect("through-hole pad must have a drill diameter");
            let hole_uuid = uuid_gen::derive(&format!("pkg-pad-hole:{mpn}:{}", pad.number));
            // A slot is a hole path of two vertices along the pad's
            // longer side, the drill diameter wide.
            let vertices = match pad.slot {
                Some(len) => {
                    let h = ((len - drill) / 2.0).max(0.0);
                    let (dx, dy) = if pad.size.0 >= pad.size.1 {
                        (h, 0.0)
                    } else {
                        (0.0, h)
                    };
                    format!(
                        "(vertex (position {:.3} {:.3}) (angle 0.0)) (vertex (position {:.3} {:.3}) (angle 0.0))",
                        -dx, -dy, dx, dy
                    )
                }
                None => "(vertex (position 0.0 0.0) (angle 0.0))".to_string(),
            };
            out.push_str(&format!(
                "   (hole {} (diameter {drill:.3}) {vertices})\n",
                fmt_uuid(hole_uuid)
            ));
        }
        out.push_str("  )\n");
    }
    out.push_str(" )\n)\n");
    out
}

/// The distinct numbers of the footprint's copper pads, in order of
/// first appearance (non-plated holes have none).
fn pad_numbers(footprint: &PcbFootprint) -> Vec<&str> {
    let mut seen = std::collections::BTreeSet::new();
    footprint
        .pads
        .iter()
        .filter(|p| p.mounting != openparts_mcad::Mounting::NonPlated)
        .map(|p| p.number.as_str())
        .filter(|n| seen.insert(*n))
        .collect()
}

/// LibrePCB's real `AssemblyType` enum (`none | tht | smt | mixed |
/// other | auto`, per LibrePCB/librepcb-parts-generator's
/// `entities/package.py`): `mixed` for SMD contacts with plated tabs
/// (USB-C receptacles). Non-plated holes don't count.
fn assembly_type(footprint: &PcbFootprint) -> &'static str {
    let (mut has_smd, mut has_tht) = (false, false);
    for pad in &footprint.pads {
        match pad.mounting {
            openparts_mcad::Mounting::Smd => has_smd = true,
            openparts_mcad::Mounting::ThroughHole => has_tht = true,
            openparts_mcad::Mounting::NonPlated => {}
        }
    }
    match (has_smd, has_tht) {
        (true, true) => "mixed",
        (false, true) => "tht",
        _ => "smt",
    }
}

fn render_component(
    mpn: &str,
    symbol: &PcbSymbol,
    cmp_uuid: Uuid,
    sym_uuid: Uuid,
    cmpcat_uuid: Uuid,
) -> String {
    let variant_uuid = uuid_gen::derive(&format!("cmp-variant:{mpn}"));
    let gate_uuid = uuid_gen::derive(&format!("cmp-gate:{mpn}"));

    let mut out = String::new();
    out.push_str(&format!("(librepcb_component {}\n", fmt_uuid(cmp_uuid)));
    out.push_str(&format!(" (name \"{mpn}\")\n"));
    out.push_str(" (description \"Generated by OpenParts from Canonical Data.\")\n");
    out.push_str(" (keywords \"\")\n");
    out.push_str(" (author \"OpenParts\")\n");
    out.push_str(" (version \"0.1\")\n");
    out.push_str(&format!(" (created {GENERATED_TIMESTAMP})\n"));
    out.push_str(" (deprecated false)\n");
    out.push_str(" (generated_by \"\")\n");
    out.push_str(&format!(" (category {})\n", fmt_uuid(cmpcat_uuid)));
    out.push_str(" (schematic_only false)\n");
    out.push_str(" (default_value \"\")\n");
    // "U" is a generator default (no reference-designator-prefix concept
    // exists in openparts-core yet), not a canonical fact.
    out.push_str(" (prefix \"U\")\n");

    for pin in &symbol.pins {
        let signal_uuid = uuid_gen::derive(&format!("cmp-signal:{mpn}:{}", pin.number));
        out.push_str(&format!(
            " (signal {} (name \"{}\") (role {})\n",
            fmt_uuid(signal_uuid),
            pin.name,
            pin_role(pin.electrical_type)
        ));
        out.push_str("  (required false) (negated false) (clock false) (forced_net \"\")\n )\n");
    }

    out.push_str(&format!(
        " (variant {} (norm \"\")\n",
        fmt_uuid(variant_uuid)
    ));
    out.push_str("  (name \"default\")\n");
    out.push_str("  (description \"\")\n");
    out.push_str(&format!("  (gate {}\n", fmt_uuid(gate_uuid)));
    out.push_str(&format!("   (symbol {})\n", fmt_uuid(sym_uuid)));
    out.push_str("   (position 0.0 0.0) (rotation 0.0) (required true) (suffix \"\")\n");
    for pin in &symbol.pins {
        let pin_uuid = uuid_gen::derive(&format!("sym-pin:{mpn}:{}", pin.number));
        let signal_uuid = uuid_gen::derive(&format!("cmp-signal:{mpn}:{}", pin.number));
        out.push_str(&format!(
            "   (pin {} (signal {}) (text signal))\n",
            fmt_uuid(pin_uuid),
            fmt_uuid(signal_uuid)
        ));
    }
    out.push_str("  )\n");
    out.push_str(" )\n)\n");
    out
}

